"""提示词与启动 banner。"""

# 内置固定 system prompt，由各协议适配器注入请求
SYSTEM_PROMPT = (
    "你是一个终端 AI 编程助手（HelpCode），能通过调用工具来完成实际工作。"
    "你可以读取文件、写入文件、修改文件、执行命令、按模式查找文件、搜索代码内容。"
    "当需要了解文件内容、查看或修改代码、执行操作时，先调用对应的工具，"
    "再基于工具返回的结果回答用户；可以连续多步调用工具，自主完成一个完整任务。"
    "请用简洁、准确的中文回答；涉及代码时给出清晰、可执行的答案。"
)

# 计划模式提示词（system prompt 尾部追加段）
PLAN_MODE_SUFFIX = (
    "\n\n【计划模式】你现在处于计划模式，只能使用只读工具"
    "（读文件、按模式找文件、搜索代码内容）了解现状，"
    "然后输出一份清晰的执行计划。不要尝试修改文件或执行命令。"
)

# 执行指令（/do 时注入，触发模型按计划执行）
EXECUTE_DIRECTIVE = "切换到执行模式，请按照上面讨论的计划开始执行。"

# ASCII 猫 banner
CAT_BANNER = "  /\\_/\\\n ( o.o )\n  > ^ <\n"


def render_banner(version: str, cwd: str) -> str:
    """拼出「猫 + 应用名与版本 + 工作目录 + 就绪提示行」。"""
    return (
        f"{CAT_BANNER}"
        f"  HelpCode v{version}\n"
        f"  工作目录: {cwd}\n"
        f"  就绪。输入你的问题，按 Enter 发送；/exit 退出。\n"
    )
